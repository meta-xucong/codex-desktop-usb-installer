"""Materialize a complete, hashed Windows cp312 wheelhouse from direct inputs.

This script intentionally produces release media under a caller-selected output
directory. It does not add binaries to the public starter kit.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
import zipfile
from email.parser import Parser
from pathlib import Path


def normalized_name(value: str) -> str:
    return re.sub(r"[-_.]+", "-", value).lower()


def read_metadata(wheel: Path) -> tuple[str, str, list[str]]:
    with zipfile.ZipFile(wheel) as archive:
        metadata_name = next(name for name in archive.namelist() if name.endswith(".dist-info/METADATA"))
        wheel_name = next(name for name in archive.namelist() if name.endswith(".dist-info/WHEEL"))
        metadata = Parser().parsestr(archive.read(metadata_name).decode("utf-8"))
        wheel_text = archive.read(wheel_name).decode("utf-8")
    tags = [line.split(":", 1)[1].strip() for line in wheel_text.splitlines() if line.startswith("Tag:")]
    return metadata["Name"], metadata["Version"], tags


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def write_json(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, required=True, help="Direct requirements .in file")
    parser.add_argument("--output", type=Path, required=True, help="Release output root")
    parser.add_argument("--python", dest="python_executable", default=sys.executable, help="cp312 interpreter used for pip download")
    parser.add_argument("--index-url", default=None, help="Optional approved package index")
    parser.add_argument(
        "--find-links",
        action="append",
        default=[],
        help="Additional local wheel directory used to satisfy packages without an approved platform wheel",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    input_path = args.input.resolve()
    output_root = args.output.resolve()
    wheelhouse = output_root / "wheelhouse"
    lock_path = output_root / "requirements-python-win-x64-py312.lock"
    manifest_path = output_root / "wheelhouse-manifest.json"
    if not input_path.is_file():
        raise SystemExit(f"Input requirements file does not exist: {input_path}")
    output_root.mkdir(parents=True, exist_ok=True)
    if wheelhouse.exists():
        shutil.rmtree(wheelhouse)
    wheelhouse.mkdir(parents=True)

    probe = "import platform,sys,sysconfig; assert sys.implementation.cache_tag == 'cpython-312'; assert sysconfig.get_platform() == 'win-amd64'; assert platform.machine() in ('AMD64','x86_64')"
    subprocess.run([args.python_executable, "-c", probe], check=True)
    command = [
        args.python_executable, "-m", "pip", "download",
        "--only-binary=:all:", "--platform", "win_amd64", "--python-version", "312",
        "--implementation", "cp", "--abi", "cp312", "--dest", str(wheelhouse),
        "--disable-pip-version-check", "--no-input", "-r", str(input_path),
    ]
    if args.index_url:
        command.extend(["--index-url", args.index_url])
    for find_links in args.find_links:
        command.extend(["--find-links", str(Path(find_links).resolve())])
    subprocess.run(command, check=True)

    records: list[dict] = []
    grouped: dict[tuple[str, str], list[str]] = {}
    for wheel in sorted(wheelhouse.glob("*.whl")):
        package, version, tags = read_metadata(wheel)
        digest = sha256(wheel)
        relative = wheel.relative_to(output_root).as_posix()
        records.append({
            "package": package,
            "normalizedPackage": normalized_name(package),
            "version": version,
            "filename": wheel.name,
            "relativePath": relative,
            "bytes": wheel.stat().st_size,
            "sha256": digest,
            "tags": tags,
        })
        grouped.setdefault((normalized_name(package), version), []).append(digest)
    if not records:
        raise SystemExit("pip download produced no wheels")

    with lock_path.open("w", encoding="utf-8", newline="\n") as lock:
        lock.write("# Generated by scripts/materialize-python-wheelhouse.py\n")
        lock.write("# Target: Windows x64 / CPython 3.12 / cp312\n")
        for (package, version), hashes in sorted(grouped.items()):
            lock.write(f"{package}=={version}")
            for digest in sorted(set(hashes)):
                lock.write(f" --hash=sha256:{digest}")
            lock.write("\n")

    payload = {
        "schemaVersion": 2,
        "materializationStatus": "ready",
        "materializationRequired": True,
        "installReady": True,
        "platform": "win_amd64",
        "python": "cpython-312",
        "abi": "cp312",
        "inputRequirements": str(input_path),
        "generatedLock": str(lock_path),
        "generatedWheelhouse": str(wheelhouse),
        "wheels": records,
        "transitiveClosure": {"required": True, "complete": True, "wheelCount": len(records), "verification": "All generated wheels are hashed and represented in the generated lock."},
    }
    write_json(manifest_path, payload)
    print(json.dumps({"materializationStatus": "ready", "wheelCount": len(records), "lock": str(lock_path), "manifest": str(manifest_path)}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
